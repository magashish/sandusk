    	  <p>Prospective volunteers shall read and complete the volunteer packet which is comprised of a volunteer application, volunteer agreement and release and waiver of liability agreement form.</p>
    	  <p>Upon completion of the volunteer packet, the prospective volunteer shall submit the three completed and signed forms to the Sandusky County Dog Shelter in person when they are ready to complete the volunteer orientation and training.</p>
    	  <p>Prospective volunteers need to complete the volunteer orientation &amp; training before volunteering at the shelter. The orientation &amp; training can be completed anytime during Sandusky County Dog Shelter hours provided an employee is available. Prospective volunteers are encouraged to call the shelter to schedule a date and time to complete the orientation and training with a shelter employee.</p>
    	  

