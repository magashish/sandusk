    	  <h2 class="head2">Volunteer Eligibility</h2>
		  <p>Prospective volunteers shall be a minimum of 18  years of age to volunteer at the shelter.</p>

		  <p>Prospective volunteers may be ineligible to volunteer if they have been criminally convicted for certain offenses under Chapter 959, Chapter 955 or other relevant chapters of the Ohio Revised Code. Eligibility is at the discretion of the Chief Dog Warden on a case by case basis.</p>
    	  <p>The Chief Dog Warden may disapprove any  prospective volunteer for any lawful reason when the Chief Dog Warden determines such action is in the best interest of the Dog  Shelter.</p>
	

